-- | A value represented only by the size of its CBOR encoding, which is
-- a byte string of exactly that many bytes.  It can stand in for any
-- encoded value, to build encodings of a chosen size.
--
newtype SizedBytes = SizedBytes { size :: Word }
  deriving (Eq, Show)

-- | Encode a CBOR byte string of exactly the given size (at least 1).  The
-- length header isn't necessarily minimal, which is valid (non-canonical)
-- CBOR.
--
encodeSizedBytes :: SizedBytes -> CBOR.Encoding
encodeSizedBytes (SizedBytes size)
    | n <= 24
    = CBOR.encodePreEncoded
    $ BS.cons (0x40 + fromIntegral (n - 1)) (BS.replicate (n - 1) 0)
    | n <= 3 + 0xffff
    = CBOR.encodePreEncoded
    $ BS.pack [0x59, byte 1 (n - 3), byte 0 (n - 3)]
   <> BS.replicate (n - 3) 0
    | otherwise
    = CBOR.encodePreEncoded
    $ BS.pack [0x5a, byte 3 (n - 5), byte 2 (n - 5), byte 1 (n - 5), byte 0 (n - 5)]
   <> BS.replicate (n - 5) 0
  where
    n :: Int
    n = max 1 (fromIntegral size)

    byte :: Int -> Int -> Word8
    byte i x = fromIntegral (x `shiftR` (8 * i))


-- | Decode a CBOR byte string, returning the size of its encoding.
--
decodeSizedBytes :: CBOR.Decoder s SizedBytes
decodeSizedBytes = do
    start <- CBOR.peekByteOffset
    _ <- CBOR.decodeBytes
    end <- CBOR.peekByteOffset
    pure (SizedBytes (fromIntegral (end - start)))


-- | Sizes of each width of the CBOR length header, and the sizes at which
-- the width changes.
--
instance Arbitrary SizedBytes where
  arbitrary = SizedBytes <$> frequency
    [ (1, elements [1, 24, 25, 3 + 0xffff, 4 + 0xffff])
    , (2, choose (1, 24))
    , (2, choose (25, 3 + 0xffff))
    , (2, choose (4 + 0xffff, 200_000))
    ]
  shrink (SizedBytes size) = [ SizedBytes s | s <- shrink size, s >= 1 ]


-- | `encodeSizedBytes` produces an encoding of the given size
--
prop_sizedBytes_encoded_size :: SizedBytes -> Property
prop_sizedBytes_encoded_size sizedBytes =
       BS.length (CBOR.toStrictByteString (encodeSizedBytes sizedBytes))
       ===
       fromIntegral (size sizedBytes)


-- | Round trip prperty for `encodeSizedBytes` and `decodeSizedBytes`.
--
prop_sizedBytes_roundtrip :: SizedBytes -> Property
prop_sizedBytes_roundtrip sizedBytes =
    case CBOR.deserialiseFromBytes decodeSizedBytes
          (CBOR.toLazyByteString (encodeSizedBytes sizedBytes)) of
      Left e -> counterexample (show e) False
      Right (trailing, sizedBytes')
        | not (BSL.null trailing)
        -> counterexample ("trailing bytes: " ++ show trailing) False
        | otherwise
        -> sizedBytes' === sizedBytes

codec_sized :: MonadST m
            => Codec (TxSubmission2 SizedBytes SizedBytes)
                     CBOR.DeserialiseFailure
                     m ByteString
codec_sized = codecTxSubmission2
              encodeSizedBytes decodeSizedBytes
              encodeSizedBytes decodeSizedBytes

-- | Bounds on the messages generated by `genBoundedMessage`.  Sizes are sizes
-- of CBOR encodings.
--
data TxSubmission2Bounds = TxSubmission2Bounds {
    tbMaxNumTxIds :: Word16,
    -- ^ maximal number of txids in a message, and of txs in a `MsgReplyTxs`
    tbMaxTxIdSize :: Word,
    -- ^ maximal size of a txid
    tbMaxTxSize   :: Word,
    -- ^ maximal size of a tx, which is sent on its own in a `MsgReplyTxs`
    tbMaxTxsSize  :: Word
    -- ^ maximal total size of the txs in a `MsgReplyTxs`, unless it carries
    -- a single tx
  }
  deriving Show

-- | Generate any message within the given bounds.  Counts and sizes are
-- biased towards the bounds.
--
genBoundedMessage :: TxSubmission2Bounds
                  -> Gen (AnyMessage (TxSubmission2 SizedBytes SizedBytes))
genBoundedMessage TxSubmission2Bounds { tbMaxNumTxIds, tbMaxTxIdSize,
                                        tbMaxTxSize, tbMaxTxsSize } =
    frequency
      [ (1, pure (AnyMessage MsgInit))
      , (1, AnyMessage <$>
              (MsgRequestTxIds SingBlocking
                <$> (NumTxIdsToAck <$> genCount 0)
                <*> (NumTxIdsToReq <$> genCount 0)))
      , (1, AnyMessage <$>
              (MsgRequestTxIds SingNonBlocking
                <$> (NumTxIdsToAck <$> genCount 0)
                <*> (NumTxIdsToReq <$> genCount 0)))
      , (2, AnyMessage . MsgReplyTxIds . BlockingReply . NonEmpty.fromList
              <$> genTxIdsAndSizes 1)
      , (2, AnyMessage . MsgReplyTxIds . NonBlockingReply
              <$> genTxIdsAndSizes 0)
      , (4, AnyMessage . MsgRequestTxs <$> genTxIds)
      , (8, AnyMessage . MsgReplyTxs <$> genTxs)
      , (1, pure (AnyMessage MsgDone))
      ]
  where
    -- a count, at least `lo`, biased towards `tbMaxNumTxIds`
    genCount :: Word16 -> Gen Word16
    genCount lo =
      frequency [ (3, pure (max lo tbMaxNumTxIds))
                , (1, choose (lo, max lo tbMaxNumTxIds))
                ]

    -- a size, biased towards `maxSize`
    genSize :: Word -> Gen Word
    genSize maxSize =
      frequency [ (3, pure (max 1 maxSize))
                , (1, choose (1, max 1 maxSize))
                ]

    -- `n` sizes: either all of them maximal, or each one chosen by `genSize`
    genSizes :: Int -> Word -> Gen [Word]
    genSizes n maxSize =
      frequency [ (3, pure (replicate n (max 1 maxSize)))
                , (1, vectorOf n (genSize maxSize))
                ]

    genTxIds :: Gen [SizedBytes]
    genTxIds = do
      n <- genCount 0
      map SizedBytes <$> genSizes (fromIntegral n) tbMaxTxIdSize

    genTxIdsAndSizes :: Word16 -> Gen [(SizedBytes, SizeInBytes)]
    genTxIdsAndSizes lo = do
      n <- genCount lo
      zip <$> (map SizedBytes <$> genSizes (fromIntegral n) tbMaxTxIdSize)
          <*> vectorOf (fromIntegral n)
                (SizeInBytes <$> frequency
                                   [ (1, pure maxBound)
                                   , (1, arbitraryBoundedIntegral)
                                   ])

    genTxs :: Gen [SizedBytes]
    genTxs = frequency
      [ (if tbMaxNumTxIds >= 1 then 1 else 0,
          (: []) . SizedBytes <$> genSize tbMaxTxSize)
      , (3, do
          -- each tx is at least one byte
          n <- min (fromIntegral tbMaxTxsSize) <$> genCount 0
          if n == 0
            then pure []
            else do
              txsSize <- frequency
                [ (3, pure tbMaxTxsSize)
                , (1, choose (fromIntegral n, tbMaxTxsSize))
                ]
              -- split `txsSize` into `n` positive sizes
              cuts <- sort <$> vectorOf (fromIntegral n - 1)
                                        (choose (0, txsSize - fromIntegral n))
              let bounds = 0 : cuts ++ [txsSize - fromIntegral n]
              pure [ SizedBytes (b - a + 1)
                   | (a, b) <- zip bounds (drop 1 bounds) ])
      ]

-- | Whether a message is within the given bounds; every message generated by
-- `genBoundedMessage` is.
--
withinBounds :: TxSubmission2Bounds
             -> AnyMessage (TxSubmission2 SizedBytes SizedBytes)
             -> Bool
withinBounds TxSubmission2Bounds { tbMaxNumTxIds, tbMaxTxIdSize,
                                   tbMaxTxSize, tbMaxTxsSize } = \case
    AnyMessage MsgInit -> True
    AnyMessage (MsgRequestTxIds _ (NumTxIdsToAck ackNo) (NumTxIdsToReq reqNo)) ->
         ackNo <= tbMaxNumTxIds
      && reqNo <= tbMaxNumTxIds
    AnyMessage (MsgReplyTxIds (BlockingReply txids)) ->
      txIdsWithin (fst <$> NonEmpty.toList txids)
    AnyMessage (MsgReplyTxIds (NonBlockingReply txids)) ->
      txIdsWithin (fst <$> txids)
    AnyMessage (MsgRequestTxs txids) ->
      txIdsWithin txids
    AnyMessage (MsgReplyTxs txs) ->
         countWithin txs
      && all ((>= 1) . size) txs
      && (   sum (size <$> txs) <= tbMaxTxsSize
          || (length txs == 1 && all ((<= max 1 tbMaxTxSize) . size) txs))
    AnyMessage MsgDone -> True
  where
    countWithin :: [a] -> Bool
    countWithin as = length as <= fromIntegral tbMaxNumTxIds

    txIdsWithin :: [SizedBytes] -> Bool
    txIdsWithin txids =
         countWithin txids
      && all (\SizedBytes { size } -> size >= 1 && size <= max 1 tbMaxTxIdSize) txids

-- | Shrink a message, keeping its constructor.  Fewer txids or txs, and
-- smaller sizes and counts, keep a message within the bounds it was
-- generated in (see `withinBounds`).
--
shrinkBoundedMessage :: AnyMessage (TxSubmission2 SizedBytes SizedBytes)
                     -> [AnyMessage (TxSubmission2 SizedBytes SizedBytes)]
shrinkBoundedMessage = \case
    AnyMessage (MsgRequestTxIds blocking ackNo reqNo) ->
         [ AnyMessage (MsgRequestTxIds blocking (NumTxIdsToAck ackNo') reqNo)
         | ackNo' <- shrink (getNumTxIdsToAck ackNo) ]
      ++ [ AnyMessage (MsgRequestTxIds blocking ackNo (NumTxIdsToReq reqNo'))
         | reqNo' <- shrink (getNumTxIdsToReq reqNo) ]
    AnyMessage (MsgReplyTxIds (BlockingReply txids)) ->
      [ AnyMessage (MsgReplyTxIds (BlockingReply txids''))
      | txids' <- shrinkList shrinkTxIdAndSize (NonEmpty.toList txids)
      , Just txids'' <- [NonEmpty.nonEmpty txids']
      ]
    AnyMessage (MsgReplyTxIds (NonBlockingReply txids)) ->
      [ AnyMessage (MsgReplyTxIds (NonBlockingReply txids'))
      | txids' <- shrinkList shrinkTxIdAndSize txids ]
    AnyMessage (MsgRequestTxs txids) ->
      [ AnyMessage (MsgRequestTxs txids') | txids' <- shrinkList shrink txids ]
    AnyMessage (MsgReplyTxs txs) ->
      [ AnyMessage (MsgReplyTxs txs') | txs' <- shrinkList shrink txs ]
    AnyMessage MsgInit -> []
    AnyMessage MsgDone -> []
  where
    shrinkTxIdAndSize :: (SizedBytes, SizeInBytes) -> [(SizedBytes, SizeInBytes)]
    shrinkTxIdAndSize (txid, SizeInBytes txSize) =
         [ (txid', SizeInBytes txSize) | txid' <- shrink txid ]
      ++ [ (txid, SizeInBytes txSize') | txSize' <- shrink txSize ]
